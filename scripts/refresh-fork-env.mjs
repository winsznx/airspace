#!/usr/bin/env node
/**
 * Refresh contracts/.env.fork from live Shannon state.
 *
 * The fork suite pins a block and two markets that share one structural domain.
 * Shannon's fast cadences retire markets within hours, so a pinned pair goes
 * stale on its own — which would make `forge test --match-path "*fork*"` an
 * unrunnable ornament rather than a gate. This regenerates the pin, so the fork
 * suite is runnable on any machine and in CI at any time.
 *
 *   node scripts/refresh-fork-env.mjs
 *   node scripts/refresh-fork-env.mjs --min-remaining 300
 */
import fs from "node:fs";
import path from "node:path";
import { createPublicClient, http } from "viem";

const RPC = process.env.SHANNON_RPC ?? "https://dream-rpc.somnia.network";
const MODULE = "0x3ecC694Cef705358864a646142ac17A90E29e388";

const arg = (n, d) => {
  const i = process.argv.indexOf(`--${n}`);
  return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : d;
};
const MIN_REMAINING = Number(arg("min-remaining", 240));

const CHAIN = {
  id: 50312,
  name: "Somnia Shannon",
  nativeCurrency: { name: "Somnia Test Token", symbol: "STT", decimals: 18 },
  rpcUrls: { default: { http: [RPC] } },
};
const client = createPublicClient({ chain: CHAIN, transport: http(RPC) });

// The module's `markets(bytes32)` tuple, in the order the deployed contract
// returns it. Verified against live reads; there is no published ABI for it.
const MODULE_ABI = [
  {
    type: "function",
    name: "markets",
    stateMutability: "view",
    inputs: [{ type: "bytes32" }],
    outputs: [
      { type: "uint256" }, { type: "uint8" }, { type: "uint8" }, { type: "address" }, { type: "uint32" },
      { type: "bytes32" }, { type: "address" }, { type: "address" }, { type: "address" }, { type: "address" },
      { type: "uint256" }, { type: "uint256" }, { type: "uint64" }, { type: "uint64" },
    ],
  },
];

async function readMarket(id) {
  let r;
  try {
    r = await client.readContract({ address: MODULE, abi: MODULE_ABI, functionName: "markets", args: [id] });
  } catch {
    // An id past the end of the registry reverts. That is "does not exist",
    // which is exactly what the binary search above is asking about.
    return null;
  }
  const pool = r[9];
  if (pool === "0x0000000000000000000000000000000000000000") return null;
  return { id, collateral: r[3], creator: r[7], pool, tradingStart: Number(r[12]), expiry: Number(r[13]) };
}

const CANONICAL = [60, 300, 900, 1800, 3600, 14400, 86400];
const cadenceOf = (start, expiry) => CANONICAL.find((c) => c >= expiry - start && expiry % c === 0) ?? 0;

const idOf = (n) => `0x${n.toString(16).padStart(64, "0")}`;

// The registry counter is dense, so the top is a binary search away.
const exists = async (n) => Boolean(await readMarket(idOf(n)));

let lo = 0x1000n;
let hi = 0x1000n;
while (await exists(hi)) {
  lo = hi;
  hi *= 2n;
  if (hi > 0x400000n) break;
}
while (lo + 1n < hi) {
  const mid = (lo + hi) / 2n;
  if (await exists(mid)) lo = mid;
  else hi = mid;
}

const now = Math.floor(Date.now() / 1000);
const byDomain = new Map();

for (let i = 0n; i < 200n && lo - i > 0n; i += 1n) {
  const m = await readMarket(idOf(lo - i));
  if (!m) continue;
  if (m.expiry - now < MIN_REMAINING) continue;
  const cadence = cadenceOf(m.tradingStart, m.expiry);
  if (!cadence) continue;
  const key = `${m.creator}|${m.collateral}|${cadence}`;
  const list = byDomain.get(key) ?? [];
  // Two markets on the SAME pool would not exercise cross-market aggregation.
  if (list.some((x) => x.pool === m.pool)) continue;
  list.push({ ...m, cadence });
  byDomain.set(key, list);
}

const pair = [...byDomain.entries()].find(([, list]) => list.length >= 2);
if (!pair) {
  console.error(
    `no domain currently has two live markets on distinct pools with >=${MIN_REMAINING}s left.\n` +
      `Shannon rolls fast — retry in a minute, or lower --min-remaining.`,
  );
  process.exit(1);
}

const [key, [m1, m2]] = pair;
const block = Number(await client.getBlockNumber());
const [creator, collateral, cadence] = key.split("|");

const out = path.join("contracts", ".env.fork");
fs.writeFileSync(
  out,
  [
    "# Generated by scripts/refresh-fork-env.mjs — do not hand-edit.",
    `# ${new Date().toISOString()}`,
    `# domain: creator ${creator} | collateral ${collateral} | cadence ${cadence}s`,
    `# ${m1.expiry - now}s and ${m2.expiry - now}s of runway at generation time.`,
    "",
    `SHANNON_RPC=${RPC}`,
    `FORK_BLOCK=${block}`,
    `MKT_1=${m1.id}`,
    `MKT_2=${m2.id}`,
    "",
  ].join("\n"),
);

console.log(`block   ${block}`);
console.log(`cadence ${cadence}s  creator ${creator.slice(0, 10)}…  collateral ${collateral.slice(0, 10)}…`);
console.log(`MKT_1   ${m1.id}  pool ${m1.pool.slice(0, 10)}…  ${m1.expiry - now}s left`);
console.log(`MKT_2   ${m2.id}  pool ${m2.pool.slice(0, 10)}…  ${m2.expiry - now}s left`);
console.log(`wrote   ${out}`);
